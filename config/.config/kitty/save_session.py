"""Save every kitty OS window, tab and window to a session file.

Each window is saved by what is running in it at save time:
  claude  -> claude --resume <CLAUDE_SESSION_ID user var>, or claude_root if unset
  nvim    -> nvim in its process cwd, loading its persistence.nvim session
  yazi    -> yazi in its cwd
  other   -> the default shell in the window's cwd (commands are never re-run)

Restore with restore_session.py. See ~/zdotdir/docs/kitty-sessions.md.
"""

import os
import re
import shlex
import subprocess
from typing import Any

from kittens.tui.handler import result_handler

SESSION_FILE = os.path.expanduser('~/.local/share/kitty/sessions/current.kitty-session')
UUID_RE = re.compile(r'^[0-9a-fA-F-]{36}$')
NVIM_RESTORE = 'nvim -c \'lua pcall(function() require("persistence").load() end)\''


def main(args: list[str]) -> None:
    pass


def find_process(window: dict[str, Any], name: str) -> dict[str, Any] | None:
    for proc in window.get('foreground_processes') or ():
        cmdline = proc.get('cmdline') or ()
        if cmdline and os.path.basename(cmdline[0]) == name:
            return proc
    return None


WAIT_ENTER = 'print -n "claude exited, press Enter to close... "; read -r'


def zsh(command: str) -> list[str]:
    return ['zsh', '-ic', f'source ~/.zshrc; {command}']


def window_spec(window: dict[str, Any]) -> tuple[str, str, list[str]]:
    """Return (kind, cwd, command); an empty command means the default shell."""
    if proc := find_process(window, 'claude'):
        session_id = (window.get('user_vars') or {}).get('CLAUDE_SESSION_ID', '')
        if UUID_RE.match(session_id):
            return 'claude', proc['cwd'], zsh(f'claude --resume {session_id}; {WAIT_ENTER}')
        return 'claude-new', proc['cwd'], zsh('claude_root')
    if proc := find_process(window, 'nvim'):
        return 'nvim', proc['cwd'], zsh(NVIM_RESTORE)
    if proc := find_process(window, 'yazi'):
        return 'yazi', proc['cwd'], zsh('yazi')
    return 'shell', window['cwd'], []


def tab_lines(tab: dict[str, Any], counts: dict[str, int]) -> list[str]:
    title = tab['title'] if tab.get('title_overridden') else ''
    lines = [f'new_tab {title}'.rstrip(), f"enabled_layouts {','.join(tab['enabled_layouts'])}", f"layout {tab['layout']}"]
    windows = {w['id']: w for w in tab['windows']}
    active_id = next((w['id'] for w in tab['windows'] if w.get('is_active')), None)
    # Groups are in layout order; the first window of a group is the base,
    # the rest are overlays (lazygit, hints, ...) which are not saved.
    for group in tab['groups']:
        window = windows.get(group['windows'][0])
        if window is None:
            continue
        kind, cwd, command = window_spec(window)
        counts[kind] = counts.get(kind, 0) + 1
        lines.append(shlex.join(['launch', f'--cwd={cwd}', *command]))
        if active_id in group['windows']:
            lines.append('focus')
    return lines


def build_session(os_windows: list[dict[str, Any]]) -> tuple[str, dict[str, int]]:
    counts: dict[str, int] = {}
    lines = ['# Generated by ~/.config/kitty/save_session.py']
    for i, os_window in enumerate(os_windows):
        if i:
            lines += ['', 'new_os_window']
        tabs = os_window['tabs']
        for tab in tabs:
            lines += ['', *tab_lines(tab, counts)]
        active_tab = next((j for j, t in enumerate(tabs) if t.get('is_active')), 0)
        lines.append(f'focus_tab {active_tab}')
    return '\n'.join(lines) + '\n', counts


def write_session(content: str) -> None:
    os.makedirs(os.path.dirname(SESSION_FILE), exist_ok=True)
    if os.path.exists(SESSION_FILE):
        os.replace(SESSION_FILE, SESSION_FILE + '.bak')
    tmp = SESSION_FILE + '.tmp'
    with open(tmp, 'w') as f:
        f.write(content)
    os.replace(tmp, SESSION_FILE)


def notify(message: str) -> None:
    script = f'display notification {json_str(message)} with title "kitty session saved"'
    subprocess.Popen(['osascript', '-e', script], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def json_str(s: str) -> str:
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


@result_handler(no_ui=True)
def handle_result(args: list[str], answer: str, target_window_id: int, boss: Any) -> None:
    os_windows = [w for w in boss.list_os_windows() if w['tabs']]
    if not os_windows:
        return
    content, counts = build_session(os_windows)
    write_session(content)
    summary = ', '.join(f'{n} {kind}' for kind, n in sorted(counts.items()))
    notify(f'{sum(len(w["tabs"]) for w in os_windows)} tabs: {summary}')
